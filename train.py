"""
train.py
--------
Full training pipeline for the Two-Stage Hierarchical KNN Color Classifier.

Pipeline overview:
  1. Load 'data/colors.csv' (generated by prepare_dataset.py).
  2. Compute a 6-dimensional cylindrical HSV + normalized RGB feature vector for each color.
  3. Split 80% train / 20% test.
  4. Scale features with StandardScaler.
  5. Find the optimal K via 3-fold cross-validation (capped at 5).
  6. Train two KNN models:
       knn_base_model  → predicts Base_English  (coarse color family)
       knn_fine_model  → predicts EnglishName   (exact shade name)
  7. Evaluate the single-stage fine KNN baseline, the Stage 1 base model,
     the real end-to-end two-stage pipeline used by predict.py
     (Stage 1 KNN + CIE Lab Delta-E retrieval), and a controlled CIE Lab
     1-NN ablation that isolates the family restriction.
  8. Build and plot a confusion matrix on 14 core color families.
  9. Serialize the full pipeline to 'model.pkl' with joblib.

Dataset:
    KopolArt Color Collection — https://kopolart.ir/colors
    Curated by Ali Yousefi (KopolArt), licensed under CC BY 4.0.
    Attribution: "کپل‌آرت – Ali Yousefi" + https://kopolart.ir/colors

Usage:
    python train.py

Outputs:
    model.pkl                      — serialized pipeline (KNN models, scaler, metadata)
    assets/confusion_matrix.png    — twin heatmap (absolute counts + normalized recall)

Requirements:
    pip install numpy pandas scikit-learn matplotlib seaborn joblib
"""

import os
import re
import sys
import warnings

import joblib
import colorsys
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.neighbors import KNeighborsClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report

# Resolve paths relative to this file so the script works from any directory.
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

# Import shared utilities from prepare_dataset.py
from prepare_dataset import hex_to_rgb, rgb_to_lab

# Ensure UTF-8 output on Windows consoles (Python 3.7+)
if hasattr(sys.stdout, 'reconfigure'):
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except Exception:
        pass

# Suppress cross-validation warnings for classes with very few samples
warnings.filterwarnings('ignore')


# ---------------------------------------------------------------------------
# Core color family patterns for the confusion matrix
# (broader than the 33 Base_English categories in the dataset)
# ---------------------------------------------------------------------------
CORE_PATTERNS = [
    ('Red',          r'\b(red|crimson|ruby|scarlet|burgundy|maroon|rose|cherry|wine|cerise)\b'),
    ('Blue',         r'\b(blue|navy|cyan|azure|indigo|sapphire|cerulean|sky|cobalt|denim|petrol|royal)\b'),
    ('Teal',         r'\b(teal|turquoise|aqua)\b'),
    ('Green',        r'\b(green|emerald|lime|olive|mint|sage|jade|forest|moss|pistachio|army)\b'),
    ('Yellow',       r'\b(yellow|amber|lemon|mustard|gold|golden|saffron)\b'),
    ('Orange',       r'\b(orange|coral|apricot|tangerine|rust)\b'),
    ('Peach',        r'\b(peach)\b'),
    ('Pink',         r'\b(pink|salmon|magenta|fuchsia|blush|flamingo)\b'),
    ('Purple',       r'\b(purple|violet|lavender|lilac|plum|mauve|amethyst|aubergine|eggplant)\b'),
    ('Brown',        r'\b(brown|chocolate|coffee|caramel|tan|mocha|chestnut|copper|bronze|cocoa|henna|camel|cinnamon|jujube)\b'),
    ('Gray',         r'\b(gray|grey|silver|charcoal|ash|slate|smoke)\b'),
    ('Black',        r'\b(black|ebony|onyx|jet)\b'),
    ('White',        r'\b(white|snow|chalk|ivory|pearl|icy|seashell|cloud|bone|milk)\b'),
    ('Beige & Cream',r'\b(beige|cream|khaki|nude|sand|sandy|vanilla|almond|wheat|champagne|honey)\b'),
]

CORE_FA_MAP = {
    'Red': 'قرمز', 'Blue': 'آبی', 'Teal': 'سبزآبی', 'Green': 'سبز',
    'Yellow': 'زرد', 'Orange': 'نارنجی', 'Peach': 'هلویی', 'Pink': 'صورتی',
    'Purple': 'بنفش', 'Brown': 'قهوه‌ای', 'Gray': 'خاکستری', 'Black': 'مشکی',
    'White': 'سفید', 'Beige & Cream': 'کرمی و بژ', 'Other': 'سایر',
}


def to_core_family(name: str) -> str:
    """Map any color name to one of the 14 core families for confusion-matrix analysis."""
    nl = str(name).strip().lower()
    for base, pat in CORE_PATTERNS:
        if re.search(pat, nl):
            return base
    return 'Other'


def hex_to_features(h: str) -> list:
    """
    Compute a 6-dimensional cylindrical HSV + normalized RGB feature vector.

    Encoding Hue as (S·cos(2πH), S·sin(2πH)) solves two problems:
      1. The 360° → 0° discontinuity in raw Hue values.
      2. Neutral colors (gray, white, black) have S ≈ 0, so the circular
         components shrink to near-zero, removing noisy Hue variation.

    Args:
        h: Hex color code string (e.g. '#388E3C').

    Returns:
        [S·cos(2πH), S·sin(2πH), V, R_norm, G_norm, B_norm]
    """
    r, g, b = hex_to_rgb(h)
    r_n, g_n, b_n = r / 255.0, g / 255.0, b / 255.0
    hh, ss, vv = colorsys.rgb_to_hsv(r_n, g_n, b_n)
    return [
        ss * np.cos(2 * np.pi * hh),   # circular Hue component 1
        ss * np.sin(2 * np.pi * hh),   # circular Hue component 2
        vv,                             # Value (brightness)
        r_n,                            # normalized Red
        g_n,                            # normalized Green
        b_n,                            # normalized Blue
    ]


# ---------------------------------------------------------------------------
# 1. Load dataset
# ---------------------------------------------------------------------------
CSV_PATH = os.path.join(BASE_DIR, "data", "colors.csv")
FALLBACK_CSV_PATH = os.path.join(BASE_DIR, "colors.csv")
MODEL_PATH = os.path.join(BASE_DIR, "model.pkl")
ASSETS_DIR = os.path.join(BASE_DIR, "assets")
CM_PATH = os.path.join(ASSETS_DIR, "confusion_matrix.png")

csv_path = CSV_PATH if os.path.exists(CSV_PATH) else FALLBACK_CSV_PATH
print(f"Loading dataset from: {csv_path}")
df = pd.read_csv(csv_path, encoding='utf-8-sig')

# Ensure alias columns exist (prepare_dataset.py adds them, but guard anyway)
if 'hex' not in df.columns and 'HexCode (24 bit)' in df.columns:
    df['hex'] = df['HexCode (24 bit)']
if 'name' not in df.columns and 'EnglishName' in df.columns:
    df['name'] = df['EnglishName']

# Build translation dictionaries
en_to_fa = dict(zip(df['EnglishName'], df['Persian Name']))
base_en_to_fa = {
    en_base: df[df['Base_English'] == en_base]['Base_Persian'].iloc[0]
    for en_base in df['Base_English'].unique()
}

# ---------------------------------------------------------------------------
# 2. Feature extraction
# ---------------------------------------------------------------------------
features = df['hex'].apply(hex_to_features)
X = np.array(features.tolist())
y_base = df['Base_English'].values    # coarse target: base color family
y_fine = df['name'].values            # fine target: exact shade name

# CIE Lab coordinates for each sample (used in Stage-2 ΔE retrieval in predict.py)
labs_all = np.array([rgb_to_lab(*hex_to_rgb(h)) for h in df['hex']])

print(f"Total samples: {len(X)}")
print(f"Base color categories: {len(set(y_base))}")
print(f"Unique exact shade names: {len(set(y_fine))}")

# ---------------------------------------------------------------------------
# 3. Train / test split (80/20, fixed random seed for reproducibility)
# ---------------------------------------------------------------------------
indices = np.arange(len(df))
train_idx, test_idx = train_test_split(indices, test_size=0.2, random_state=42)

X_train, X_test = X[train_idx], X[test_idx]
y_base_train, y_base_test = y_base[train_idx], y_base[test_idx]
y_fine_train, y_fine_test = y_fine[train_idx], y_fine[test_idx]
df_train = df.iloc[train_idx].copy().reset_index(drop=True)
labs_train = labs_all[train_idx]

# ---------------------------------------------------------------------------
# 4. Feature scaling
# ---------------------------------------------------------------------------
scaler = StandardScaler()
X_train_s = scaler.fit_transform(X_train)
X_test_s  = scaler.transform(X_test)

# ---------------------------------------------------------------------------
# 5. Hyperparameter search: find optimal K via 3-fold cross-validation
#    The search is capped at K=5 to avoid over-smoothing with this dataset size.
# ---------------------------------------------------------------------------
best_k, best_score = 1, 0.0
for k in range(1, min(21, len(X_train))):
    knn_cv = KNeighborsClassifier(n_neighbors=k, weights='distance')
    score = cross_val_score(knn_cv, X_train_s, y_base_train, cv=3).mean()
    if score > best_score:
        best_score, best_k = score, k

optimal_k = max(1, min(best_k, 5))  # cap at 5 to avoid over-smoothing
print(f"\nOptimal K: {optimal_k}  (raw CV best: {best_k}, CV score: {best_score:.3f})")

# ---------------------------------------------------------------------------
# 6. Train two KNN models
#    knn_base_model : predicts Base_English  (used in Stage 1)
#    knn_fine_model : predicts EnglishName   (used for strict-match accuracy only)
# ---------------------------------------------------------------------------
knn_base_model = KNeighborsClassifier(n_neighbors=optimal_k, weights='distance')
knn_base_model.fit(X_train_s, y_base_train)

knn_fine_model = KNeighborsClassifier(n_neighbors=optimal_k, weights='distance')
knn_fine_model.fit(X_train_s, y_fine_train)

pred_base = knn_base_model.predict(X_test_s)
pred_fine = knn_fine_model.predict(X_test_s)

# ---------------------------------------------------------------------------
# 7. Multi-tier accuracy evaluation
# ---------------------------------------------------------------------------
strict_acc = accuracy_score(y_fine_test, pred_fine)
base_acc   = accuracy_score(y_base_test, pred_base)

# Human-vision accuracy: counts as correct if both true and predicted names
# belong to the same core color family (e.g. 'Dark Red' vs 'Red' → both 'Red')
human_matches = sum(
    to_core_family(y_fine_test[i]) == to_core_family(pred_fine[i])
    for i in range(len(y_fine_test))
)
human_acc = human_matches / len(y_fine_test)

# Top-3 human-vision accuracy for the single-stage fine KNN baseline
_, fine_neighbor_idx = knn_fine_model.kneighbors(X_test_s)
fine_top3_human = sum(
    any(
        to_core_family(y_fine_test[i])
        == to_core_family(y_fine_train[fine_neighbor_idx[i][j]])
        for j in range(3)
    )
    for i in range(len(y_fine_test))
) / len(y_fine_test)

# ---------------------------------------------------------------------------
# 7b. End-to-end two-stage evaluation
#
# This is the pipeline actually used by predict.py:
#   Stage 1: KNN → base color family
#   Stage 2: CIE Lab Delta-E nearest-neighbor search inside that family
#
# The metrics below are separate from the fine-KNN baseline above. Reporting
# both is important: the two-stage pipeline trades some strict exact-match
# accuracy for better human-vision agreement with the predicted family.
# ---------------------------------------------------------------------------
labs_test = labs_all[test_idx]


def two_stage_top3_names(features_scaled, query_lab):
    """Return the top-3 shade names retrieved by the two-stage pipeline."""
    pred_base_en = knn_base_model.predict(features_scaled)[0]
    base_mask = (df_train["Base_English"] == pred_base_en)

    if not np.any(base_mask):
        candidate_sub = df_train
        candidate_labs = labs_train
    else:
        candidate_sub = df_train[base_mask].reset_index(drop=True)
        candidate_labs = labs_train[base_mask.values]

    distances = np.linalg.norm(candidate_labs - query_lab, axis=1)
    order = np.argsort(distances)[:3]
    return candidate_sub.iloc[order]["EnglishName"].tolist()


two_stage_top3 = [
    two_stage_top3_names(X_test_s[i:i + 1], labs_test[i])
    for i in range(len(X_test_s))
]
two_stage_pred = [names[0] for names in two_stage_top3]

two_stage_strict = accuracy_score(y_fine_test, two_stage_pred)
two_stage_human = sum(
    to_core_family(y_fine_test[i]) == to_core_family(two_stage_pred[i])
    for i in range(len(y_fine_test))
) / len(y_fine_test)
two_stage_top3_human = sum(
    any(to_core_family(y_fine_test[i]) == to_core_family(name) for name in names)
    for i, names in enumerate(two_stage_top3)
) / len(y_fine_test)

# ---------------------------------------------------------------------------
# 7c. Controlled ablation: single-stage 1-NN in CIE Lab
#
# The fine-KNN baseline above uses the 6-D scaled feature space and K=optimal_k,
# so it differs from the two-stage pipeline in both feature space and neighbour
# count. This ablation uses 1-NN in the same CIE Lab space as Stage 2 but
# searches the entire training set, which isolates the effect of the Stage 1
# family restriction.
# ---------------------------------------------------------------------------
lab_nn = KNeighborsClassifier(n_neighbors=1, metric="euclidean")
lab_nn.fit(labs_train, y_fine_train)
lab_top3_idx = lab_nn.kneighbors(labs_test, n_neighbors=3, return_distance=False)
lab_top1 = y_fine_train[lab_top3_idx[:, 0]]

lab_strict = accuracy_score(y_fine_test, lab_top1)
lab_human = sum(
    to_core_family(y_fine_test[i]) == to_core_family(lab_top1[i])
    for i in range(len(y_fine_test))
) / len(y_fine_test)
lab_top3_human = sum(
    any(
        to_core_family(y_fine_test[i]) == to_core_family(y_fine_train[j])
        for j in lab_top3_idx[i]
    )
    for i in range(len(y_fine_test))
) / len(y_fine_test)

print("\n" + "=" * 62)
print("Performance Summary — Main Pipeline")
print("=" * 62)
print("Single-stage fine KNN (313 shade classes) — baseline")
print(f"  Strict exact-match accuracy : {strict_acc * 100:.1f}%")
print(f"  Human-vision accuracy       : {human_acc * 100:.1f}%")
print(f"  Top-3 human-vision accuracy : {fine_top3_human * 100:.1f}%")
print("\nStage 1 base KNN (33 color families)")
print(f"  Base-family accuracy        : {base_acc * 100:.1f}%")
print("\nControlled ablation: single-stage 1-NN in CIE Lab (no family filter)")
print(f"  Strict exact-match accuracy : {lab_strict * 100:.1f}%")
print(f"  Human-vision accuracy       : {lab_human * 100:.1f}%")
print(f"  Top-3 human-vision accuracy : {lab_top3_human * 100:.1f}%")
print("\nEnd-to-end two-stage pipeline (Stage 1 KNN + CIE Lab retrieval)")
print(f"  Strict exact-match accuracy : {two_stage_strict * 100:.1f}%")
print(f"  Human-vision accuracy       : {two_stage_human * 100:.1f}%")
print(f"  Top-3 human-vision accuracy : {two_stage_top3_human * 100:.1f}%")

# ---------------------------------------------------------------------------
# 8. Confusion matrix on 14 core color families
#
# Note: The confusion matrix is built by mapping both true labels (from
# y_fine_test) and predictions (from pred_base) through to_core_family(),
# which collapses compound families like 'Navy Blue' → 'Blue'.
# This gives an intuitive view of cross-family errors.
# ---------------------------------------------------------------------------
y_core_true = [to_core_family(name) for name in y_fine_test]
y_core_pred = [to_core_family(name) for name in pred_base]

# Only keep labels that actually appear in true or predicted sets
core_labels = [
    'Blue', 'Green', 'Orange', 'Peach', 'Yellow', 'Red', 'Pink', 'Purple',
    'Brown', 'Gray', 'Black', 'White', 'Beige & Cream', 'Teal'
]
core_labels = [c for c in core_labels if c in set(y_core_true) or c in set(y_core_pred)]
cm_display_labels = [lbl for lbl in core_labels]

cm = confusion_matrix(y_core_true, y_core_pred, labels=core_labels)
df_cm = pd.DataFrame(cm, index=cm_display_labels, columns=cm_display_labels)

print("\n" + "=" * 55)
print("Confusion Matrix (Core Color Families):")
print("=" * 55)
print(df_cm.to_string())

print("\n" + "=" * 55)
print("Classification Report:")
print("=" * 55)
print(classification_report(
    y_core_true, y_core_pred,
    labels=core_labels,
    target_names=cm_display_labels,
    zero_division=0,
))

# ---------------------------------------------------------------------------
# Plot and save twin heatmaps (absolute counts + normalized recall)
# ---------------------------------------------------------------------------
fig, axes = plt.subplots(1, 2, figsize=(20, 8))

# Left: absolute counts
sns.heatmap(df_cm, annot=True, fmt='d', cmap='Blues', cbar=True, square=True, ax=axes[0])
axes[0].set_title('Absolute Confusion Matrix', fontsize=13, fontweight='bold', pad=12)
axes[0].set_xlabel('Predicted Label', fontsize=10, labelpad=8)
axes[0].set_ylabel('True Label', fontsize=10, labelpad=8)
axes[0].tick_params(axis='x', rotation=45)

# Right: row-normalized (recall per class)
cm_norm = cm.astype('float') / cm.sum(axis=1)[:, np.newaxis]
cm_norm = np.nan_to_num(cm_norm)
df_cm_norm = pd.DataFrame(cm_norm, index=cm_display_labels, columns=cm_display_labels)

sns.heatmap(df_cm_norm, annot=True, fmt='.2f', cmap='YlGnBu', cbar=True, square=True, ax=axes[1])
axes[1].set_title('Normalized Confusion Matrix (Row-Recall)', fontsize=13, fontweight='bold', pad=12)
axes[1].set_xlabel('Predicted Label', fontsize=10, labelpad=8)
axes[1].set_ylabel('True Label', fontsize=10, labelpad=8)
axes[1].tick_params(axis='x', rotation=45)

plt.suptitle('Color Classification — Confusion Matrix & Error Analysis', fontsize=16, fontweight='bold')
plt.tight_layout()
os.makedirs(ASSETS_DIR, exist_ok=True)
plt.savefig(CM_PATH, dpi=150, bbox_inches='tight')
plt.close()
print(f"\nSaved: {CM_PATH}")

# ---------------------------------------------------------------------------
# 9. Serialize the full pipeline to model.pkl
# ---------------------------------------------------------------------------
pipeline_data = {
    "model":                   knn_fine_model,
    "knn_base_model":          knn_base_model,
    "scaler":                  scaler,
    "train_df":                df_train,
    "labs_train":              labs_train,
    "base_en_to_fa":           base_en_to_fa,
    "en_to_fa":                en_to_fa,
    "confusion_matrix":        cm,
    "confusion_matrix_labels": core_labels,
    "confusion_matrix_df":     df_cm,
}
joblib.dump(pipeline_data, MODEL_PATH)
print(f"Saved: {MODEL_PATH}  (full pipeline — both KNN models, scaler, metadata)")
